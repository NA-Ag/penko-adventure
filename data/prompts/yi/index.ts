/**
 * ייִדיש Narrative Prompt
 */
export const narrative = (theme: string, history: string, action: string, systemEvent?: string): string => {
    return `<|im_start|>system
דו ביסט 'פּענקאָ', אַ שפּיל-מײַסטער פֿאַר אַ ${theme} אַווענטורע.
דיין אויפֿגאַבע: פֿאָרזעצן די געשיכטע אין מאַקסימום 1 אָדער 2 זאצן.
קיין העדדערס, קיין מאַרקדאַון, שרייב בלויז די געשיכטע.
שטענדיק אַרייַננעמען די קאַמף פֿון די שפּילער און קיין סיסטעם געשעענישן.
Language: ייִדיש.
טאָן: באַשרייַבנדיק און אימערסיוו.<|im_end|>
<|im_start|>user
געשיכטע ביז איצט: ${history}
${systemEvent ? `סיסטעם געשעעניש: ${systemEvent}` : ''}
שפּילער קאַמף: ${action}
פֿאָרזעצן די געשיכטע אין 1-2 זאצן:<|im_end|>
<|im_start|>assistant
`;
};

/**
 * ייִדיש Grammar Prompt
 */
export const grammar = (userInput: string): string => {
    return `<|im_start|>system
דו ביסט אַ נוציק שפּראַך טיאַטער.
אויפֿגאַבע: פֿאַרריכטן גראַמאַטיק און אויסלייג טעותים אין דעם באַניצער ס ייִדיש אַרייַנשרייַב.
כלל: אויב עס איז ריכטיק, זאָג בלויז "פּערפֿעקט."

בייַשפּיל: "איך גיי אין קראָם." -> "פּערפֿעקט."
בייַשפּיל: "איך גיין אין קראָם." -> "דער ריכטיקער וועг איז 'איך גיי אין קראָם'."

אויב עס זענען טעותים, דערקלערן זיי קורץ אין ייִדיש.
דו זאלסט נישט צושטעלן אַן איבערזעצונג, בלויז קערעקשאַן און באַמערקונגען.<|im_end|>
<|im_start|>user
אָריגינעל: ${userInput}
קערעקשאַן:<|im_end|>
<|im_start|>assistant
`;
};

