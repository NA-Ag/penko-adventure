export const narrative = (language: string, levelName: string, scenario: Scenario, history: string, action: string, systemEvent?: string): string => {
    const local = LOCALIZED_SCENARIOS[scenario.id] || { title: scenario.title, role: scenario.systemPrompt, objectives: scenario.objectives };

    return `<|im_start|>system
ИИ учител по езици (${levelName}). ${local.role}
Правило на Берлиц: НЕ поправяйте директно. Потвърдете идеята, като използвате правилната граматика естествено.
Пример: Ученик: "Аз яде торта вчера" -> Ти: "Аз също **ядох** торта вчера, какъв вкус харесваш?"

Сценарий: ${local.title}
Цели: ${local.objectives.join(', ')}

Правила:
1. ТОЧНО 1 или 2 кратки изречения.
2. Език: ${language}. АНГЛИЙСКИЯТ Е ЗАБРАНЕН.
3. Ниво: ${levelName}.<|im_end|>
<|im_start|>user
Разговор: ${history}
${systemEvent ? `Събитие: ${systemEvent}` : ''}
Ученик: ${action}
Отговор на учителя:<|im_end|>
<|im_start|>assistant
`;
};

export const grammar = (userInput: string): string => {
    return `<|im_start|>system
Езиков учител. Поправяй грешките в написаното от потребителя. Ако е правилно, кажи „Перфектно“ (Perfect).<|im_end|>
<|im_start|>user
Оригинал: ${userInput}
Поправка:<|im_end|>
<|im_start|>assistant
`;
};

