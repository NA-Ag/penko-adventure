/**
 * GBC-Style Sprite Definitions
 *
 * Sprites are defined as 2D pixel arrays (like Game Boy Color tile data)
 * Each sprite is 8x8 or 16x16 pixels
 *
 * Color palette:
 * 0 = transparent
 * 1 = dark color (outline/shadow)
 * 2 = mid color (body)
 * 3 = light color (highlight)
 * 4 = accent color (eyes, special features)
 */

export type SpriteFrame = number[][];
export type SpriteAnimation = SpriteFrame[];

export interface SpriteSet {
  idle: SpriteAnimation;
  walk?: SpriteAnimation;
}

